// src/Pages/modules/operations/components/customer/AccountProfileSheet.jsx
import { Kv, KvGrid, SheetSection, SheetHeader, MiniTable, Tick, dotDate, nowStamp } from './ProfileBits';
import { amountInWordsBD } from '../../utils/numberToWords';

const CONTACT_COLS = [
  { key: 'label', label: 'Contact' }, { key: 'name', label: 'Name' }, { key: 'designation', label: 'Designation' },
  { key: 'mobile', label: 'Phone (Cell)' }, { key: 'email', label: 'E-mail' },
];
const UPDATE_TYPES = [['N_GAIN', 'N. Gain'], ['R_GAIN', 'R. Gain'], ['AC_UPDATE', 'A/C Update']];
const DEPARTMENTS = ['Sales', 'Cr. Control', 'Accounts', 'Ops'];
const sum = (rows, k) => rows.reduce((t, r) => t + (Number(r[k]) || 0), 0);

const AccountProfileSheet = ({ client: c }) => {
  const p = c.profile || {};
  const r = c.recommendation || {};
  const rows = c.projected || [];
  const contacts = c.contacts || [];
  const key = contacts.find((x) => x.type === 'Key Contact Person');
  const fin = contacts.find((x) => x.type === 'Finance Contact');
  const contactRows = [key && { label: 'Contact Person', ...key }, fin && { label: 'Accounts Person', ...fin }].filter(Boolean);
  const destinations = p.destinations || [...new Set(rows.map((x) => x.country))].join(', ');
  const services = c.serviceRequired || [];
  const limit = Number(c.creditLimitAmount) || 0;

  return (
    <div className="text-slate-800">
      <SheetHeader customerId={c.customerId} title="Account Profile" right={<><p>Effective Date: <b>{p.effectiveDate || '—'}</b></p><p>Closing Date: <b>{p.closingDate || '—'}</b></p></>} />

      <SheetSection title="Company Information">
        <KvGrid>
          <Kv k="Company Name" v={c.accountName} /><Kv k="Name of Managing Partner" v={c.managingPartner} /><Kv k="Address" v={c.address} />
          <Kv k="Phone" v={c.mobile} /><Kv k="Fax" v={c.fax} /><Kv k="E-mail" v={c.email} />
        </KvGrid>
      </SheetSection>

      <SheetSection title="Customer Information">
        <MiniTable columns={CONTACT_COLS} rows={contactRows} empty="No contacts recorded." />
        <KvGrid className="sm:grid-cols-2 mt-2"><Kv k="BIN Number" v={p.binNumber} /><Kv k="TIN Number" v={p.tinNumber} /></KvGrid>
      </SheetSection>

      <SheetSection title="Shipping Detail">
        <KvGrid className="sm:grid-cols-2 lg:grid-cols-3">
          <Kv k="Volume" v={rows.length ? sum(rows, 'avgVolume') : ''} /><Kv k="Weight" v={rows.length ? sum(rows, 'weightKg') : ''} /><Kv k="Revenue ($)" v={rows.length ? sum(rows, 'revenueUsd') : ''} />
          <Kv k="Preferred Carrier" v={p.preferredCarrier} /><Kv k="Destinations" v={destinations} /><Kv k="Nature of Business" v={p.natureOfBusiness} />
        </KvGrid>
      </SheetSection>

      <SheetSection title="Account Detail">
        <div className="space-y-2 mb-2">
          <div><span className="text-[10px] font-bold text-slate-400 uppercase mr-3">Service Required</span><Tick label="OB" checked={services.includes('OB')} /><Tick label="IB" checked={services.includes('IB')} /></div>
          <div><span className="text-[10px] font-bold text-slate-400 uppercase mr-3">Type</span>{UPDATE_TYPES.map(([code, label]) => <Tick key={code} label={label} checked={(p.accountUpdateType || []).includes(code)} />)}</div>
          <div><span className="text-[10px] font-bold text-slate-400 uppercase mr-3">Type of Account</span><Tick label="Cash" checked={c.accountType === 'Cash'} /><Tick label="Credit" checked={c.accountType === 'Credit'} /></div>
        </div>
        <KvGrid className="sm:grid-cols-2 lg:grid-cols-4">
          <Kv k="Account Mode" v={c.accountMode} /><Kv k="Area" v={c.area} /><Kv k="Zone" v={c.zone} /><Kv k="Rate Ref. No." v={r.rateRefNo} />
          <Kv k="Date" v={dotDate(p.date)} /><Kv k="Business Type" v={c.businessType} /><Kv k="Approved Rate" v={r.approvedRateText} className="sm:col-span-2" />
          <Kv k="Amount Limit (BDT)" v={limit ? limit.toLocaleString('en-US') : ''} /><Kv k="Time Limit (Days)" v={c.creditPeriodDays} /><Kv k="(In Word)" v={limit ? amountInWordsBD(limit) : ''} className="sm:col-span-2" />
          <Kv k="Account Created By" v={p.accountCreatedBy} /><Kv k="Account Handled By" v={p.accountHandledBy} />
          <Kv k="Special Instructions (If Any)" v={p.specialInstructions} className="sm:col-span-2" />
          <Kv k="Checked By" v={p.checkedBy} /><Kv k="Approved By" v={p.approvedBy} />
        </KvGrid>
        <div className="mt-3 pt-2 border-t border-slate-100"><span className="text-[10px] font-bold text-slate-400 uppercase mr-3">Distributed Departments</span>{DEPARTMENTS.map((d) => <Tick key={d} label={d} checked={(p.distributedTo || []).includes(d)} />)}</div>
      </SheetSection>

      <p className="text-[9px] text-slate-400 mt-4">This account profile was generated by the MILEXAIR system on {nowStamp()}. No signature is required for the system generated copy.</p>
    </div>
  );
};

export default AccountProfileSheet;
import { OPERATIONS_ROLES as R } from './operationsRoles';

export const OPERATIONS_PERMISSIONS = Object.freeze({
  VIEW_DASHBOARD: 'VIEW_DASHBOARD',
  CREATE_DRAFT: 'CREATE_DRAFT',
  CONFIRM_COMMERCIAL: 'CONFIRM_COMMERCIAL',
  EDIT_CENTRAL_DOCUMENTS: 'EDIT_CENTRAL_DOCUMENTS',
  REQUEST_GATE: 'REQUEST_GATE',
  DECIDE_GATE: 'DECIDE_GATE',
  ASSIGN_TASK: 'ASSIGN_TASK',
  COMPLETE_TASK: 'COMPLETE_TASK',
  HUB_VERIFY: 'HUB_VERIFY',
  ORIGIN_ACTUALS: 'ORIGIN_ACTUALS',
  UPLOAD_EVIDENCE: 'UPLOAD_EVIDENCE',
  VERIFY_EVIDENCE: 'VERIFY_EVIDENCE',
  MANUAL_TRACKING: 'MANUAL_TRACKING',
  CLOSE_SHIPMENT: 'CLOSE_SHIPMENT',
  AUDIT_ALL: 'AUDIT_ALL',
});

const P = OPERATIONS_PERMISSIONS;

export const OPERATIONS_ROLE_PERMISSIONS = Object.freeze({
  [R.CLIENT]: [P.VIEW_DASHBOARD, P.CREATE_DRAFT, P.CONFIRM_COMMERCIAL],
  [R.OPERATIONS_HEAD]: Object.values(P),
  [R.DOMESTIC_ADMIN]: [
    P.VIEW_DASHBOARD, P.CREATE_DRAFT, P.EDIT_CENTRAL_DOCUMENTS, P.REQUEST_GATE, P.ASSIGN_TASK,
    P.HUB_VERIFY, P.VERIFY_EVIDENCE, P.MANUAL_TRACKING, P.CLOSE_SHIPMENT,
  ],
  [R.FOREIGN_ADMIN]: [P.VIEW_DASHBOARD, P.ORIGIN_ACTUALS, P.UPLOAD_EVIDENCE],
  [R.COURIER]: [P.VIEW_DASHBOARD, P.COMPLETE_TASK],
  [R.CNF]: [P.VIEW_DASHBOARD, P.UPLOAD_EVIDENCE],
});

export const hasOperationsPermission = (role, permission) =>
  Array.isArray(OPERATIONS_ROLE_PERMISSIONS[role]) && OPERATIONS_ROLE_PERMISSIONS[role].includes(permission);

export const hasAnyOperationsPermission = (role, permissions = []) =>
  permissions.some((p) => hasOperationsPermission(role, p));
// Creates the document drafts right after the booking form, and keeps untouched drafts in sync when the booking data is edited.
import { fetchLatestDocuments, saveDocument } from './documentService';
import { buildInvoiceData, buildPackingData, buildDeclarationData, buildAwbData } from '../utils/draftDocs';

export const createDraftDocuments = async (s, { items = [], comment = '', termsAccepted = false } = {}, actor) => {
  const filled = items.filter((i) => i.description);
  const save = (type, data) => saveDocument({ shipmentId: s.shipmentId, type, data, changeSummary: 'Auto-created from the booking form' }, actor);
  if (filled.length) await save('INVOICE', buildInvoiceData(s, filled, comment));
  await save('PACKING_LIST', buildPackingData(s));
  if (s.mode !== 'IMPORT') await save('DECLARATION', buildDeclarationData(s)); // Declaration is export-only
  await save('AWB', buildAwbData(s, termsAccepted));
  // Import: the shipping label is generated by the system in the overseas-courier label layout.
  if (s.mode === 'IMPORT') await save('LABEL', { generated: true, source: 'MILEX', labelStatus: 'GENERATED' });
};

// Only drafts nobody has edited by hand (autoDraft === true) are refreshed. Hand-edited versions are never touched.
export const refreshDraftDocuments = async (s, actor) => {
  const latest = await fetchLatestDocuments(s.shipmentId);
  const builders = {
    PACKING_LIST: () => buildPackingData(s),
    ...(s.mode === 'IMPORT' ? {} : { DECLARATION: () => buildDeclarationData(s) }),
    AWB: (doc) => buildAwbData(s, !!doc.data?.termsAccepted),
  };
  for (const [type, build] of Object.entries(builders)) {
    const doc = latest[type];
    if (!doc?.data?.autoDraft || doc.status !== 'DRAFT') continue;
    const data = build(doc);
    if (JSON.stringify(data) === JSON.stringify(doc.data)) continue;
    await saveDocument({ shipmentId: s.shipmentId, type, data, changeSummary: 'Auto-updated from the booking data' }, actor);
  }
};